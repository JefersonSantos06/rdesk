/// How to inject a key on Windows.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum WinKey {
    /// Set-1 scan code; `ext` = needs `KEYEVENTF_EXTENDEDKEY` (the 0xE0 prefix).
    Scan { code: u16, ext: bool },
    /// Virtual-key code, for keys without a usable scan code (Pause).
    Vk(u16),
}

