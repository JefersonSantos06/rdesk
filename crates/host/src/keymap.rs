#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    /// Keys that legitimately have no code on a platform.
    const MAC_UNMAPPED: &[Key] = &[
        Key::F21,
        Key::F22,
        Key::F23,
        Key::F24,
        Key::Convert,
        Key::NonConvert,
        Key::MediaPlayPause,
        Key::MediaStop,
        Key::MediaTrackNext,
        Key::MediaTrackPrevious,
    ];

    #[test]
    fn windows_covers_every_key_uniquely() {
        let mut seen = HashMap::new();
        for &k in Key::ALL {
            let code = windows(k).unwrap_or_else(|| panic!("{k:?} unmapped on Windows"));
            if let Some(prev) = seen.insert(code, k) {
                panic!("{k:?} and {prev:?} share {code:?}");
            }
        }
    }

    #[test]
    fn evdev_covers_every_key_uniquely() {
        let mut seen = HashMap::new();
        for &k in Key::ALL {
            let code = evdev(k).unwrap_or_else(|| panic!("{k:?} unmapped on Linux"));
            assert!(code + 8 <= 255, "{k:?} does not fit an X11 keycode");
            if let Some(prev) = seen.insert(code, k) {
                panic!("{k:?} and {prev:?} share {code}");
            }
        }
    }

    #[test]
    fn macos_covers_every_key_except_known_gaps() {
        for &k in Key::ALL {
            assert_eq!(macos(k).is_none(), MAC_UNMAPPED.contains(&k), "{k:?}");
        }
    }

    #[test]
    fn abnt2_keys_are_mapped() {
        // Brazilian ABNT2 boards use these two extra keys.
        for k in [Key::IntlBackslash, Key::IntlRo] {
            assert!(windows(k).is_some() && evdev(k).is_some() && macos(k).is_some());
        }
    }
}
